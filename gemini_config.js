// Gemini 호출 설정을 한 곳에 모은다.
//
// 예전에는 스크립트마다 모델 이름을 따로 적었다.
//   auto_fetch_news.js  gemini-3.6-flash
//   auto_fb_sync.js     gemini-flash-latest
// 이러면 한쪽만 고치고 다른 쪽을 잊는다. 실제로 2026-08 중순에
// 은퇴한 모델을 두 주 동안 부르며 요약이 통째로 멈춘 적이 있다.

module.exports = {
  // 실제로 요약이 나온 것이 확인된 모델
  MODEL: 'gemini-3.6-flash',

  // 위 모델이 은퇴하면 이걸로 한 번 더 시도한다.
  // 이름이 고정된 모델은 언젠가 반드시 404 가 되고, 별칭은 그때 살아남는다.
  MODEL_FALLBACK: 'gemini-flash-latest',

  // 호출 간격(ms).
  //
  // 2026-09-05 에 4500 → 9000 으로 늘렸다. 분당 한도가 원인이라고 봤는데
  // 틀렸다. 회차 소요는 그대로 129~157분이었다.
  // 2026-09-07 에 API 응답으로 진짜 원인이 나왔다 — 분당이 아니라 하루다.
  //   quotaId    GenerateRequestsPerDayPerProjectPerModel-FreeTier
  //   quotaValue 20
  // 간격은 분당 한도용으로만 의미가 있으니 9초를 그대로 둔다.
  CALL_INTERVAL_MS: 9000,

  // 한 회차에 언어당 요약할 최대 건수.
  //
  // 하루 한도 20회 ÷ 기사당 2회(요약 + 코리케어 시선) = 하루 10건이 천장이다.
  // 3언어이므로 언어당 3건이면 18회. 한도 안에 들어온다.
  // 예전 값 10은 3언어 × 2회 = 60회로, 첫 회차에서 이미 3배 초과였다.
  //
  // 이 숫자를 올리려면 먼저 호출을 합쳐야 한다.
  //   요약 + 시선을 한 번에 받으면          60 → 30
  //   3개 언어를 한 번에 받으면             30 → 10
  // 그때 LIMIT_PER_LANG 를 다시 올린다.
  LIMIT_PER_LANG: 3,

  // 429(호출 한도)일 때 재시도 횟수와 대기
  RETRY: 2,
  RETRY_WAIT_MS: 20000
};
