// Gemini 호출 설정을 한 곳에 모은다.
//
// 예전에는 스크립트마다 모델 이름을 따로 적었다.
//   auto_fetch_news.js  gemini-3.6-flash
//   auto_fb_sync.js     gemini-flash-latest
// 이러면 한쪽만 고치고 다른 쪽을 잊는다. 실제로 2026-08 중순에
// 은퇴한 모델을 두 주 동안 부르며 요약이 통째로 멈춘 적이 있다.

module.exports = {
  // 실제로 요약이 나온 것이 확인된 모델
  MODEL: 'gemini-3.6-flash',

  // 위 모델이 은퇴하면 이걸로 한 번 더 시도한다.
  // 이름이 고정된 모델은 언젠가 반드시 404 가 되고, 별칭은 그때 살아남는다.
  MODEL_FALLBACK: 'gemini-flash-latest',

  // 호출 간격(ms). 무료 등급은 분당 15회 안팎이라 쉬지 않고 던지면
  // 앞의 스무 건만 통과하고 나머지는 전부 429 로 튕긴다.
  // 실측: 한 회차 300건 중 20건만 요약됨.
  //
  // 4500 → 9000 으로 늘렸다 (2026-09-05).
  // 기사 한 건에 호출이 두 번(요약 + 코리케어 시선) 들어가면서 회차당
  // 60회가 됐는데, 4.5초 간격은 분당 13회라 매 회차 한도에 걸렸다.
  // 걸리면 summarizeOnce 가 모델 2개 × 재시도 2회 × 20초 = 한 호출에
  // 80초를 잔다. 그래서 회차 소요가 94~200분이 됐다 (최근 15회 실측).
  // 아껴서 빨리 던지는 쪽이 오히려 7배 느리다. 9초면 분당 6.6회다.
  CALL_INTERVAL_MS: 9000,

  // 한 회차에 언어당 요약할 최대 건수.
  // 10건 × 3언어 × 하루 6회 = 180건. 목록이 언어당 50건이므로
  // 하루면 전부 요약본으로 갈린다.
  LIMIT_PER_LANG: 10,

  // 429(호출 한도)일 때 재시도 횟수와 대기
  RETRY: 2,
  RETRY_WAIT_MS: 20000
};
