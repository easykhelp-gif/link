// Gemini 호출 설정을 한 곳에 모은다.
//
// 예전에는 스크립트마다 모델 이름을 따로 적었다.
//   auto_fetch_news.js  gemini-3.6-flash
//   auto_fb_sync.js     gemini-flash-latest
// 이러면 한쪽만 고치고 다른 쪽을 잊는다. 실제로 2026-08 중순에
// 은퇴한 모델을 두 주 동안 부르며 요약이 통째로 멈춘 적이 있다.

// 무료 등급의 하루 한도는 모델마다 25배까지 차이가 난다.
// AI Studio 의 프로젝트별 실제 한도 화면에서 직접 읽은 값이다 (2026-09-07, koricare).
//
//   Gemini 3.6 Flash        분당 5 · 하루 20
//   Gemini 3.7 Flash        분당 5 · 하루 20
//   Gemini 3.8 Flash        분당 5 · 하루 20
//   Gemini 3.5 Flash Lite   분당 15 · 하루 500     ← 25배
//
// Flash 를 쓰던 동안은 하루 20회가 천장이라 회차마다 요약이 0건이었다.
// Lite 로 옮기면 하루 500회다. 요약 품질은 조금 떨어지지만
// 3줄 뉴스 요약과 짧은 번역에는 충분하고, 0건보다는 낫다.
module.exports = {
  MODEL: 'gemini-3.5-flash-lite',

  // 위 모델이 은퇴하면 이걸로 한 번 더 시도한다.
  // 같은 Lite 계열로 둔다. gemini-flash-latest 는 Flash 를 가리켜
  // 하루 20회짜리라 대체 모델로서 값이 없다.
  MODEL_FALLBACK: 'gemini-3.1-flash-lite',

  // 호출 간격(ms). Lite 는 분당 15회까지 되므로 5초면 분당 12회다.
  //
  // 이 값을 두고 두 번 헛짚었다. 기록으로 남긴다.
  //   2026-09-05  4500 → 9000. 분당 한도가 원인이라고 봤는데 틀렸다
  //   2026-09-07  API 응답으로 진짜 원인이 나왔다 — 분당이 아니라 하루 20회였다
  //   2026-09-07  그마저도 절반만 맞았다. 하루 20회는 Flash 계열의 한도이고
  //               모델을 Lite 로 바꾸면 하루 500회다
  CALL_INTERVAL_MS: 5000,

  // 한 회차에 언어당 요약할 최대 건수.
  //
  // 하루 예산 500회. 기사 한 건에 2회(요약 + 코리케어 시선)가 든다.
  //   10건 × 3언어 × 2회 = 회차당 60회
  //   하루 4회 실행        = 240회      → 한도 500 의 절반이 남는다
  LIMIT_PER_LANG: 10,

  // 429(호출 한도)일 때 재시도 횟수와 대기
  RETRY: 2,
  RETRY_WAIT_MS: 20000
};
